// ── Parse Text & Render Live Preview ──
function parseTextAndUpdatePreview() {
    const rawText = document.getElementById('raw-text-input')?.value || '';
    const lines = rawText.split(/\r?\n/);
    const blocks = [];
    let autoL1Counter = 1;

    for (let i = 0; i < lines.length; i++) {
        const rawLine = lines[i].trim();
        if (!rawLine) continue;

        // Optional Markdown Headings (# = Level 1, ## = Level 2, etc.)
        const mdMatch = rawLine.match(/^(#{1,5})\s+(.*)$/);
        if (mdMatch) {
            const lvl = mdMatch[1].length;
            let num = '';
            if (lvl === 1) {
                num = autoL1Counter + '.';
                autoL1Counter++;
            }
            blocks.push({
                type: lvl === 1 ? 'level1' : `level${lvl}`,
                level: lvl,
                number: num,
                text: mdMatch[2].trim()
            });
            continue;
        }

        // Level 5: 5-level numbering (e.g. 1.1.1.1.1 [Text])
        const l5Match = rawLine.match(/^(\d+\.\d+\.\d+\.\d+\.\d+)\.?\s+(.*)$/);
        if (l5Match) {
            blocks.push({
                type: 'level5',
                level: 5,
                number: l5Match[1],
                text: l5Match[2].trim()
            });
            continue;
        }

        // Level 4: 4-level numbering (e.g. 1.1.1.1 [Text]) or Bullets
        const l4Match = rawLine.match(/^(\d+\.\d+\.\d+\.\d+)\.?\s+(.*)$/);
        if (l4Match) {
            blocks.push({
                type: 'level4',
                level: 4,
                number: l4Match[1],
                text: l4Match[2].trim()
            });
            continue;
        }
        const bulletMatch = rawLine.match(/^([•\-\*\u2022\u2023\u25E6\u2043\u2219])\s+(.*)$/);
        if (bulletMatch) {
            blocks.push({
                type: 'level4',
                level: 4,
                number: '•',
                text: bulletMatch[2].trim()
            });
            continue;
        }

        // Level 3: 3-level numbering (e.g. 1.1.1 [Text])
        const l3Match = rawLine.match(/^(\d+\.\d+\.\d+)\.?\s+(.*)$/);
        if (l3Match) {
            blocks.push({
                type: 'level3',
                level: 3,
                number: l3Match[1],
                text: l3Match[2].trim()
            });
            continue;
        }

        // Level 2: 2-level numbering (e.g. 1.1 [Text])
        const l2Match = rawLine.match(/^(\d+\.\d+)\.?\s+(.*)$/);
        if (l2Match) {
            blocks.push({
                type: 'level2',
                level: 2,
                number: l2Match[1],
                text: l2Match[2].trim()
            });
            continue;
        }

        // Level 1: 1-level numbering (e.g. 1. [Text] or 1. NAME or 1. Our Vision)
        const l1Match = rawLine.match(/^(\d+)\.\s+(.*)$/);
        if (l1Match) {
            const explicitNum = parseInt(l1Match[1], 10);
            if (!isNaN(explicitNum)) {
                autoL1Counter = explicitNum + 1;
            }
            blocks.push({
                type: 'level1',
                level: 1,
                number: l1Match[1] + '.',
                text: l1Match[2].trim()
            });
            continue;
        }

        // Level 1: Section / Article / Roman numeral prefixes (e.g. SECTION 1, ARTICLE I, I., II.)
        const secMatch = rawLine.match(/^(SECTION|ARTICLE|CHAPTER|CLAUSE|PART|SCHEDULE|ANNEXURE)\s+([A-Z0-9\.\:\-]+)\s*(\:|\-|\–)?\s*(.*)$/i);
        if (secMatch) {
            const title = secMatch[4] ? secMatch[4].trim() : secMatch[0];
            blocks.push({
                type: 'level1',
                level: 1,
                number: `${secMatch[1]} ${secMatch[2]}`,
                text: title
            });
            continue;
        }

        const romanL1 = rawLine.match(/^(I|II|III|IV|V|VI|VII|VIII|IX|X|XI|XII|XIII|XIV|XV)\.\s+(.*)$/i);
        if (romanL1) {
            blocks.push({
                type: 'level1',
                level: 1,
                number: romanL1[1] + '.',
                text: romanL1[2].trim()
            });
            continue;
        }

        // Level 1: Standalone All-Caps Lines (e.g. 'OUR VISION', 'CODE OF CONDUCT')
        if (/^[A-Z0-9\s\&\,\-\(\)\:\/\|]{3,65}$/.test(rawLine) && !rawLine.startsWith('http') && !rawLine.includes('EMIS:') && !rawLine.endsWith('.')) {
            const num = autoL1Counter + '.';
            autoL1Counter++;
            blocks.push({
                type: 'level1',
                level: 1,
                number: num,
                text: rawLine.trim()
            });
            continue;
        }

        // Level 1: Common unnumbered headings (e.g. 'Our Vision', 'Our Mission', 'Our Core Values', 'Our Goals', 'Our Values')
        const lower = rawLine.toLowerCase().replace(/[\:\-\–\—]+$/, '').trim();
        const isNamedHeading = /^(our vision|vision|our mission|mission|our core values|core values|our values|values|our goals|strategic goals|aims and objectives|objectives|preamble|introduction|background|purpose|scope|guiding principles|policy statement|definitions|roles and responsibilities|code of conduct|adoption and sign-off|sign-off resolution|resolution)/.test(lower);
        
        // Or any short standalone title-cased heading without terminal sentence punctuation
        const isShortHeading = rawLine.length <= 45 &&
            !rawLine.endsWith('.') &&
            !rawLine.endsWith(',') &&
            !rawLine.endsWith(';') &&
            /^[A-Z]/.test(rawLine) &&
            rawLine.split(/\s+/).length <= 6 &&
            (isNamedHeading || rawLine.startsWith('Our ') || rawLine.endsWith(' Statement') || rawLine.endsWith(' Values') || rawLine.endsWith(' Policy'));

        if (isNamedHeading || isShortHeading) {
            const num = autoL1Counter + '.';
            autoL1Counter++;
            blocks.push({
                type: 'level1',
                level: 1,
                number: num,
                text: rawLine.replace(/[\:\-\–\—]+$/, '').trim()
            });
            continue;
        }

        // Everything else without numbering is a regular Body Paragraph
        blocks.push({
            type: 'body',
            level: 0,
            number: '',
            text: rawLine
        });
    }

    state.parsedBlocks = blocks;

    // Update Stats Badge
    const statsBadge = document.getElementById('parsed-stats-badge');
    if (statsBadge) {
        const l1Count = blocks.filter(b => b.type === 'level1').length;
        const clauseCount = blocks.filter(b => b.type !== 'level1' && b.type !== 'body').length;
        statsBadge.textContent = `${l1Count} Headings • ${clauseCount} Clauses`;
    }

    renderDocumentPreview();
    scheduleBackgroundSpellCheck();
}

