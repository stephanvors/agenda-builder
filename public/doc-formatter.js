async function generateAndExportDocument() {
    const statusBox = document.getElementById('generation-status');
    const genBtn = document.getElementById('btn-generate-doc');

    if (statusBox) {
        statusBox.classList.remove('hidden');
        statusBox.innerHTML = `<div class="spinner-row"><span>Compiling formatted document with hanging indents...</span></div>`;
    }
    if (genBtn) genBtn.disabled = true;

    try {
        const config = collectCurrentConfig();
        const rawText = document.getElementById('raw-text-input')?.value || '';
        const outputFormat = document.querySelector('input[name="output-format"]:checked')?.value || 'docx';
        const saveTarget = document.querySelector('input[name="save-target"]:checked')?.value || 'download';
        const serverPath = document.getElementById('custom-server-path')?.value || '';
        const vaultCategory = document.getElementById('vault-category-select')?.value || 'Governance & Policy';
        const vaultTag = document.getElementById('vault-tag-select')?.value || 'Policies';

        const payload = {
            config,
            rawText,
            outputFormat,
            saveTarget,
            serverPath,
            vaultCategory,
            vaultTag
        };

        const res = await fetch('/api/doc-formatter/generate', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                ...(state.token ? { 'Authorization': 'Bearer ' + state.token } : {})
            },
            body: JSON.stringify(payload)
        });

        if (!res.ok) {
            const err = await res.json();
            throw new Error(err.error || 'Failed to generate document');
        }

        // Check if response is JSON (vault/server save) or Blob download
        const contentType = res.headers.get('Content-Type') || '';
        if (contentType.includes('application/json')) {
            const result = await res.json();
            statusBox.innerHTML = `
                <div style="color: #10B981; font-weight: bold; margin-bottom: 4px;">✅ Document Generated &amp; Published!</div>
                <div>${escapeHTML(result.message || 'Saved successfully.')}</div>
                ${result.docxUrl ? `<a href="${result.docxUrl}" class="btn btn-sm btn-outline mt-2" download>Download DOCX</a> ` : ''}
                ${result.pdfUrl ? `<a href="${result.pdfUrl}" class="btn btn-sm btn-outline mt-2" download>Download PDF</a> ` : ''}
            `;
            showToast('Document created successfully!');
        } else {
            // Blob file download
            const blob = await res.blob();
            const disposition = res.headers.get('Content-Disposition') || '';
            let filename = 'LGAA_Formatted_Document.' + (outputFormat === 'pdf' ? 'pdf' : 'docx');
            const match = disposition.match(/filename="?([^";]+)"?/);
            if (match && match[1]) filename = match[1];

            const downloadUrl = window.URL.createObjectURL(blob);
            const a = document.createElement('a');
            a.href = downloadUrl;
            a.download = filename;
            document.body.appendChild(a);
            a.click();
            a.remove();
            window.URL.revokeObjectURL(downloadUrl);

            statusBox.innerHTML = `
                <div style="color: #10B981; font-weight: bold;">✅ Download Started!</div>
                <div>File <strong>${escapeHTML(filename)}</strong> has been downloaded to your computer.</div>
            `;
            showToast('Document downloaded!');
        }
    } catch (e) {
        console.error(e);
        if (statusBox) {
            statusBox.innerHTML = `<div style="color: #EF4444; font-weight: bold;">❌ Error: ${escapeHTML(e.message)}</div>`;
        }
        showToast(e.message, true);
    } finally {
        if (genBtn) genBtn.disabled = false;
    }
}

