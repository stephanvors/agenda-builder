// ── File Upload Handler ──
function handleUploadedFile(file) {
    if (!file) return;

    const ext = file.name.split('.').pop().toLowerCase();
    if (ext === 'txt' || ext === 'md') {
        const reader = new FileReader();
        reader.onload = (e) => {
            document.getElementById('raw-text-input').value = e.target.result;
            parseTextAndUpdatePreview();
            showToast('Uploaded ' + file.name + ' successfully.');
        };
        reader.readAsText(file);
    } else {
        // Send file to server for text extraction
        const formData = new FormData();
        formData.append('rawFile', file);

        showToast('Extracting text from ' + file.name + '...');
        fetch('/api/doc-formatter/parse-raw', {
            method: 'POST',
            headers: state.token ? { 'Authorization': 'Bearer ' + state.token } : {},
            body: formData
        })
        .then(res => res.json())
        .then(data => {
            if (data.rawText) {
                document.getElementById('raw-text-input').value = data.rawText;
                parseTextAndUpdatePreview();
                showToast('Extracted document text.');
            } else if (data.error) {
                showToast(data.error, true);
            }
        })
        .catch(err => {
            console.error(err);
            showToast('Failed to parse document: ' + err.message, true);
        });
    }
}

